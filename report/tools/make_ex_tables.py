"""Generate the data tables of Part B from measured run files. No model calls, no network.

SciMKG/runs/ is not tracked by Git, so the generated .tex files in report/tables/ are committed instead.
Rerun this whenever the inputs change, after the analysis steps that produce them:
    SciMKG/scripts/experiments/ex-01/analyze.py   (Ex01 API-style tokens and unit costs)
    SciMKG/scripts/experiments/ex-02/run.py summary
    SciMKG/scripts/experiments/ex-03/run.py evaluate

Usage:
    python3 report/tools/make_ex_tables.py [--run SciMKG/runs/pipeline/<model>/<lesson>] [--outdir DIR]

Two token measures are used and kept apart:
    CLI tokens       what the command-line tool reports; each call carries a fixed context of about 12 thousand tokens
    API-style tokens prompt and schema counted with o200k_base (plus estimated image tokens), without that context
Money is therefore a range: the API-style figure is the lower bound, the CLI figure (with cache pricing) the upper bound.
The script also prints the numbers quoted in the report text, so the prose can be checked against the data.
"""
import argparse
import csv
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
RUNS = ROOT / "SciMKG/runs"
ANALYSIS = RUNS / "analysis"
DEFAULT_RUN = RUNS / "pipeline/gpt-6-luna/nervous-system"
MOOC = RUNS / "preprocessing/mooc"
PRICES = ROOT / "SciMKG/scripts/experiments/ex-01/prices.json"
DEFAULT_OUTDIR = ROOT / "report/tables"
MODEL = "gpt-6-luna"
GENERATED = "% Generated by report/tools/make_ex_tables.py from measured run files; do not edit by hand."

# Counts from the SciMKG paper (report Mục sec:sm-store). Clips are used as segments: an assumption, stated in the text.
PAPER_CLIPS = 10425
PAPER_IMAGES = 10527
PAPER_CONCEPTS = 34630

# stage key in the cost files -> row label
STAGES = [
    ("E", "Trích xuất (E)"),
    ("V", "Kiểm chứng (V)"),
    ("I", "Tích hợp (I)"),
    ("A", "Bổ sung (A) và truy hồi nguồn"),
    ("explanation", "Tạo giải thích"),
    ("image_alignment", "Căn chỉnh ảnh"),
    ("audio", "Tạo âm thanh (cục bộ)"),
]
# cost.csv column -> name used below
COLUMNS = {
    "calls_new": "llm_attempts",
    "calls_retry": "llm_retries",
    "input_tokens": "input_tokens_cli",
    "cached_input_tokens": "cached_input_tokens_cli",
    "output_tokens": "output_tokens_cli",
    "usage_missing_calls": "usage_missing",
    "stage_wall_seconds": "stage_wall_seconds",
}
LESSONS = [
    ("nervous-system", "Cấu tạo hệ thần kinh"),
    ("amphibian-reproduction", "Sinh sản của động vật lưỡng cư"),
    ("atmospheric-pressure", "Áp suất khí quyển"),
    ("buoyancy", "Lực đẩy"),
    ("sulfuric-acid-and-sulfate", "Axit sunfuric và muối sunfat"),
    ("proteins", "Protein"),
]
CONFIGS = [("no-verification", "0 vòng"), ("one-round", "1 vòng"), ("full", "5 vòng")]
METHODS = [
    ("random", "Ngẫu nhiên (mốc dưới)"),
    ("bm25-transcript", "BM25 trên toàn văn bản ghi (mốc trên)"),
    ("graph-no-verification-first", "Đồ thị, đoạn đầu, kiểm chứng 0 vòng"),
    ("graph-one-round-first", "Đồ thị, đoạn đầu, kiểm chứng 1 vòng"),
    ("graph-full-first", "Đồ thị, đoạn đầu, kiểm chứng 5 vòng"),
    ("graph-no-verification-every", "Đồ thị, mọi đoạn có nhắc, kiểm chứng 0 vòng"),
    ("graph-one-round-every", "Đồ thị, mọi đoạn có nhắc, kiểm chứng 1 vòng"),
    ("graph-full-every", "Đồ thị, mọi đoạn có nhắc, kiểm chứng 5 vòng"),
]
PRICE_ROWS = ["GPT-4o", "DeepSeek-V3", "Gemini-1.5-Flash", "gpt-5.6-terra", "gpt-6.1-sol", "gpt-6-luna"]
PRICE_KEYS = ["gpt-4o", "deepseek-v3", "gemini-1.5-flash", "gpt-5.6-terra", "gpt-6.1-sol", "gpt-6-luna"]


def read_csv(path):
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def vn_int(n):
    return f"{int(round(n)):,}".replace(",", ".")


def vn_float(x, digits=1):
    return f"{x:.{digits}f}".replace(".", ",")


def vn_pct(x):
    return vn_float(100 * x, 1) + "\\%"


def vn_money(x):
    # small values keep three decimals so they stay readable
    if x < 0.1:
        return vn_float(x, 3)
    if x < 100:
        return vn_float(x, 2)
    return vn_int(x)


def vn_ratio(x):
    return vn_float(x, 3)


def read_run(run):
    rows = {r["stage"]: r for r in read_csv(run / "cost.csv")}
    return {k: {name: float(rows[k][col] or 0) for name, col in COLUMNS.items()} for k, _ in STAGES}


def read_api_stages():
    rows = read_csv(ANALYSIS / "ex01" / MODEL / "cost_by_stage.csv")
    return {r["name"]: {"calls": float(r["calls"]), "input": float(r["api_input"]), "output": float(r["api_output"])}
            for r in rows if r["level"] == "stage"}


def ex01_table(run):
    cli = read_run(run)
    api = read_api_stages()
    for key, _ in STAGES:
        if round(api[key]["calls"]) != round(cli[key]["calls_new"]):
            raise ValueError(f"call count differs between CLI and API-style counts at {key}")
        if round(api[key]["output"]) != round(cli[key]["output_tokens"]):
            raise ValueError(f"output tokens differ between CLI and API-style counts at {key}")
    total = {f: sum(cli[k][f] for k, _ in STAGES) for f in COLUMNS}
    api_input = sum(api[k]["input"] for k, _ in STAGES)
    tokens_all = total["input_tokens"] + total["output_tokens"]

    lines = [
        GENERATED,
        "\\begin{tabular}{@{}lrrrrrrr@{}}",
        "\\toprule",
        "Bước & Lượt gọi & \\begin{tabular}[c]{@{}r@{}}Token vào,\\\\CLI\\end{tabular}"
        " & \\begin{tabular}[c]{@{}r@{}}trong đó\\\\đã lưu sẵn\\end{tabular}"
        " & \\begin{tabular}[c]{@{}r@{}}Token vào,\\\\kiểu API\\end{tabular}"
        " & Token ra & \\begin{tabular}[c]{@{}r@{}}Tỉ lệ\\\\tổng token\\end{tabular} & Thời gian (phút) \\\\",
        "\\midrule",
    ]
    for key, label in STAGES:
        t = cli[key]
        share = (t["input_tokens"] + t["output_tokens"]) / tokens_all
        lines.append(
            f"{label} & {vn_int(t['calls_new'])} & {vn_int(t['input_tokens'])} & {vn_int(t['cached_input_tokens'])}"
            f" & {vn_int(api[key]['input'])} & {vn_int(t['output_tokens'])}"
            f" & {vn_pct(share)} & {vn_float(t['stage_wall_seconds'] / 60)} \\\\"
        )
    lines += [
        "\\midrule",
        f"\\textbf{{Tổng}} & \\textbf{{{vn_int(total['calls_new'])}}} & \\textbf{{{vn_int(total['input_tokens'])}}}"
        f" & \\textbf{{{vn_int(total['cached_input_tokens'])}}} & \\textbf{{{vn_int(api_input)}}}"
        f" & \\textbf{{{vn_int(total['output_tokens'])}}} & \\textbf{{100\\%}}"
        f" & \\textbf{{{vn_float(total['stage_wall_seconds'] / 60)}}} \\\\",
        "\\bottomrule",
        "\\end{tabular}",
    ]
    report = {
        "calls": total["calls_new"], "retries": total["calls_retry"], "missing_usage": total["usage_missing_calls"],
        "cli_input": total["input_tokens"], "cli_cached": total["cached_input_tokens"], "output": total["output_tokens"],
        "api_input": api_input, "minutes": total["stage_wall_seconds"] / 60,
        "input_share_of_all_cli": total["input_tokens"] / tokens_all,
        "fixed_context_share": {k: 1 - api[k]["input"] / cli[k]["input_tokens"] for k in ("E", "V", "A", "explanation")},
    }
    return lines, report


def image_split(api_input):
    headline = json.loads((ANALYSIS / "ex01" / MODEL / "headline.json").read_text(encoding="utf-8"))
    # each image is sent in three alignment calls, so its tokens appear three times in the API-style input
    image_in = 3 * headline["image_tokens_estimated"]
    return {"image_in": image_in, "text_in": api_input - image_in, "image_per_image_call": headline["image_tokens_estimated"]}


def ex02_quality_table():
    by_run = {(r["configuration"], r["lesson_id"]): r for r in read_csv(ANALYSIS / "ex02" / MODEL / "per_run.csv")}
    macro = {r["configuration"]: r for r in read_csv(ANALYSIS / "ex02" / MODEL / "by_configuration.csv")}
    for cfg, _ in CONFIGS:
        for metric, column in (("precision", "macro_precision"), ("recall", "macro_recall"), ("f1", "macro_f1")):
            mean = sum(float(by_run[(cfg, lesson)][metric]) for lesson, _ in LESSONS) / len(LESSONS)
            if abs(mean - float(macro[cfg][column])) > 0.0005:
                raise ValueError(f"mean of {metric} for {cfg} does not match by_configuration.csv")

    lines = [
        GENERATED,
        "\\begin{tabular}{@{}lccccccccc@{}}",
        "\\toprule",
        " & \\multicolumn{3}{c}{0 vòng} & \\multicolumn{3}{c}{1 vòng} & \\multicolumn{3}{c}{5 vòng (đầy đủ)} \\\\",
        "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(l){8-10}",
        "Bài & P & R & F1 & P & R & F1 & P & R & F1 \\\\",
        "\\midrule",
    ]
    for lesson, label in LESSONS:
        cells = []
        for cfg, _ in CONFIGS:
            row = by_run[(cfg, lesson)]
            cells += [vn_ratio(float(row["precision"])), vn_ratio(float(row["recall"])), vn_ratio(float(row["f1"]))]
        lines.append(f"{label} & " + " & ".join(cells) + " \\\\")
    lines.append("\\midrule")
    cells = []
    for cfg, _ in CONFIGS:
        m = macro[cfg]
        cells += [f"\\textbf{{{vn_ratio(float(m['macro_precision']))}}}", f"\\textbf{{{vn_ratio(float(m['macro_recall']))}}}",
                  f"\\textbf{{{vn_ratio(float(m['macro_f1']))}}}"]
    lines += ["\\textbf{Trung bình} & " + " & ".join(cells) + " \\\\", "\\bottomrule", "\\end{tabular}"]
    return lines


def ex02_summary_table():
    macro = {r["configuration"]: r for r in read_csv(ANALYSIS / "ex02" / MODEL / "by_configuration.csv")}
    rows_per_run = read_csv(ANALYSIS / "ex02" / MODEL / "per_run.csv")
    substring = {cfg: sum(float(r["substring_f1"]) for r in rows_per_run if r["configuration"] == cfg) / len(LESSONS)
                 for cfg, _ in CONFIGS}
    spec = [
        ("Precision", lambda c, m: vn_ratio(float(m["macro_precision"]))),
        ("Recall", lambda c, m: vn_ratio(float(m["macro_recall"]))),
        ("F1", lambda c, m: vn_ratio(float(m["macro_f1"]))),
        ("F1 khớp chuỗi con (thăm dò)", lambda c, m: vn_ratio(substring[c])),
        ("Trần recall của E", lambda c, m: vn_ratio(float(m["macro_pool_recall"]))),
        ("Số lời gọi, sáu bài", lambda c, m: vn_int(float(m["calls"]))),
        ("Token vào, kiểu API", lambda c, m: vn_int(float(m["api_input"]))),
        ("Token ra, kiểu API", lambda c, m: vn_int(float(m["api_output"]))),
        ("Chi phí, USD (Luna, cận dưới)", lambda c, m: vn_money(float(m["api_cost_usd"]))),
        ("Bài có F1 thấp hơn cấu hình 5 vòng", lambda c, m: m["f1_below_full"] or "–"),
    ]
    lines = [
        GENERATED,
        "\\begin{tabular}{@{}lccc@{}}",
        "\\toprule",
        "Chỉ số (trung bình sáu bài) & 0 vòng & 1 vòng & 5 vòng \\\\",
        "\\midrule",
    ]
    for label, cell in spec:
        lines.append(label + " & " + " & ".join(cell(cfg, macro[cfg]) for cfg, _ in CONFIGS) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return lines


def ex03_table():
    rows = {(r["query_type"], r["method"]): r for r in read_csv(ANALYSIS / "ex03" / MODEL / "by_method.csv")}
    lines = [
        GENERATED,
        "\\begin{tabular}{@{}lrrrrrrrr@{}}",
        "\\toprule",
        " & \\multicolumn{4}{c}{Câu nguyên văn} & \\multicolumn{4}{c}{Câu viết lại} \\\\",
        "\\cmidrule(lr){2-5}\\cmidrule(l){6-9}",
        "Cách tìm & Hit@1 & Hit@3 & MRR & Độ phủ & Hit@1 & Hit@3 & MRR & Độ phủ \\\\",
        "\\midrule",
    ]
    # separators: after the two reference rows, and before the "every" group
    separate_before = {"graph-no-verification-first", "graph-no-verification-every"}
    for method, label in METHODS:
        if method in separate_before:
            lines.append("\\midrule")
        cells = []
        for query_type in ("verbatim", "rewritten"):
            r = rows[(query_type, method)]
            cells += [vn_ratio(float(r["macro_hit1"])), vn_ratio(float(r["macro_hit3"])),
                      vn_ratio(float(r["macro_mrr"])), vn_ratio(float(r["macro_coverage"]))]
        lines.append(label + " & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    return lines


def graph_unit_costs():
    """Per-unit API-style tokens: segments from the six Ex02 lessons (E, V and A together), images and concepts from Ex01."""
    segments = sum(len(json.loads((MOOC / lesson / "lesson.json").read_text(encoding="utf-8"))["segments"])
                   for lesson, _ in LESSONS)
    summary = {r["configuration"]: r for r in read_csv(ANALYSIS / "ex02" / MODEL / "by_configuration.csv")}
    units = {r["key"]: r for r in read_csv(ANALYSIS / "ex01" / MODEL / "unit_costs.csv")}
    return {
        "segments_measured": segments,
        "segment_in": float(summary["full"]["api_input"]) / segments,
        "segment_out": float(summary["full"]["api_output"]) / segments,
        "image_in": float(units["image"]["api_input_tokens_per_unit"]),
        "image_out": float(units["image"]["api_output_tokens_per_unit"]),
        "concept_in": float(units["explanation"]["api_input_tokens_per_unit"]),
        "concept_out": float(units["explanation"]["api_output_tokens_per_unit"]),
    }


def price_table(run):
    prices = json.loads(PRICES.read_text(encoding="utf-8"))["models"]
    api = read_api_stages()
    api_in = sum(v["input"] for v in api.values())
    api_out = sum(v["output"] for v in api.values())
    cli = read_run(run)
    cli_in = sum(cli[k]["input_tokens"] for k, _ in STAGES)
    cli_cached = sum(cli[k]["cached_input_tokens"] for k, _ in STAGES)
    cli_out = sum(cli[k]["output_tokens"] for k, _ in STAGES)
    unit = graph_unit_costs()
    graph_in = (PAPER_CLIPS * unit["segment_in"] + PAPER_IMAGES * unit["image_in"] + PAPER_CONCEPTS * unit["concept_in"])
    graph_out = (PAPER_CLIPS * unit["segment_out"] + PAPER_IMAGES * unit["image_out"] + PAPER_CONCEPTS * unit["concept_out"])

    lines = [
        GENERATED,
        "\\begin{tabular}{@{}lcccccc@{}}",
        "\\toprule",
        "Mô hình & Giá nhập & \\begin{tabular}[c]{@{}c@{}}Giá nhập\\\\đã lưu sẵn\\end{tabular} & Giá xuất"
        " & \\begin{tabular}[c]{@{}c@{}}Một bài,\\\\cận dưới\\end{tabular}"
        " & \\begin{tabular}[c]{@{}c@{}}Một bài,\\\\cận trên\\end{tabular}"
        " & \\begin{tabular}[c]{@{}c@{}}Cả đồ thị,\\\\cận dưới\\end{tabular} \\\\",
        "\\midrule",
    ]
    report = {}
    for label, key in zip(PRICE_ROWS, PRICE_KEYS):
        p = prices[key]
        if p["input"] is None:
            lines.append(f"{label} & – & – & – & chưa xác minh & chưa xác minh & – \\\\")
            continue
        lower = (api_in * p["input"] + api_out * p["output"]) / 1e6
        upper = ((cli_in - cli_cached) * p["input"] + cli_cached * p["cached_input"] + cli_out * p["output"]) / 1e6
        graph = (graph_in * p["input"] + graph_out * p["output"]) / 1e6
        report[key] = {"lower": lower, "upper": upper, "graph_lower": graph}
        cached = vn_float(p["cached_input"], 2) if p["cached_input"] is not None else "–"
        # one-lesson costs keep three decimals so the lower bound stays readable next to the upper one
        lines.append(f"{label} & {vn_float(p['input'], 2)} & {cached} & {vn_float(p['output'], 2)}"
                     f" & {vn_float(lower, 3)} & {vn_float(upper, 3)} & {vn_money(graph)} \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    report["_graph"] = {"units": unit, "graph_in": graph_in, "graph_out": graph_out,
                        "api_in": api_in, "api_out": api_out, "cli_in": cli_in, "cli_cached": cli_cached, "cli_out": cli_out}
    return lines, report


def write(path, lines):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    try:
        shown = path.resolve().relative_to(ROOT)
    except ValueError:
        shown = path
    print("wrote", shown)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--run", type=pathlib.Path, default=DEFAULT_RUN)
    ap.add_argument("--outdir", type=pathlib.Path, default=DEFAULT_OUTDIR)
    args = ap.parse_args()

    lines, cost = ex01_table(args.run)
    write(args.outdir / "ex01_cost.tex", lines)
    print("Ex01 totals:", {k: round(v, 3) for k, v in cost.items() if isinstance(v, float)})
    print("  fixed-context share of CLI input per step:", {k: round(v, 4) for k, v in cost["fixed_context_share"].items()})
    print("  API-style input split:", image_split(cost["api_input"]))

    write(args.outdir / "ex02_quality.tex", ex02_quality_table())
    write(args.outdir / "ex02_summary.tex", ex02_summary_table())
    write(args.outdir / "ex03_retrieval.tex", ex03_table())

    lines, price = price_table(args.run)
    write(args.outdir / "ex_price.tex", lines)
    for key, values in price.items():
        if key == "_graph":
            continue
        print(f"price {key}: one lesson lower {values['lower']:.6f} upper {values['upper']:.6f}; "
              f"whole graph lower {values['graph_lower']:.2f} USD")
    graph = price["_graph"]
    print("graph units", {k: round(v, 1) if isinstance(v, float) else v for k, v in graph["units"].items()})
    print(f"graph API-style input {vn_int(graph['graph_in'])}, output {vn_int(graph['graph_out'])}")


if __name__ == "__main__":
    main()
