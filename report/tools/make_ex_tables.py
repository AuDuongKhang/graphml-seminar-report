"""Generate the Ex01 cost table of the report from the measured cost files.

Reads <run>/current/cost.csv and <run>/completed/cost.csv (incremental cost of each
ConceptNet variant), adds the two variants step by step and writes a LaTeX tabular to
report/tables/ex01_cost.tex. SciMKG/runs/ is not tracked by Git, so the generated table is
committed; rerun this script (and commit the result) whenever Ex01 is rerun.

Usage:
    python3 report/tools/make_ex_tables.py [--run SciMKG/runs/experiments/ex-01/<run-dir>] [--out FILE]

Only tokens, calls and time are reported; money is derived from tokens in the report text
(price per model changes), so no price column is written here.
"""
import argparse
import csv
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
# The 13/10/2026 run (protocol 2) is archived until Ex01 is rerun with the current code.
DEFAULT_RUN = ROOT / "SciMKG/runs/archived/ex-01/nervous-system-20261013"
DEFAULT_OUT = ROOT / "report/tables/ex01_cost.tex"

# stage key in cost.csv -> row label (steps that are not measured are named in the caption)
STAGES = [
    ("E", "Trích xuất (E)"),
    ("V", "Kiểm chứng (V)"),
    ("I", "Tích hợp (I)"),
    ("A", "Bổ sung (A) và truy hồi nguồn"),
    ("explanation", "Tạo giải thích"),
    ("image_alignment", "Căn chỉnh ảnh"),
    ("audio", "Tạo âm thanh (cục bộ)"),
]
VARIANTS = ("current", "completed")
FIELDS = ("calls_new", "calls_retry", "input_tokens", "cached_input_tokens", "output_tokens",
          "usage_missing_calls", "stage_wall_seconds")


def read_variant(run, variant):
    with open(run / variant / "cost.csv", encoding="utf-8", newline="") as f:
        rows = {r["stage"]: r for r in csv.DictReader(f)}
    return {k: {x: float(rows[k][x] or 0) for x in FIELDS} for k, _ in STAGES}


def vn_int(n):
    return f"{int(round(n)):,}".replace(",", ".")


def vn_float(x, digits=1):
    return f"{x:.{digits}f}".replace(".", ",")


def vn_pct(x):
    return vn_float(100 * x, 1) + "\\%"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--run", type=pathlib.Path, default=DEFAULT_RUN)
    ap.add_argument("--out", type=pathlib.Path, default=DEFAULT_OUT)
    args = ap.parse_args()

    per_variant = {v: read_variant(args.run, v) for v in VARIANTS}
    total = {k: {f: sum(per_variant[v][k][f] for v in VARIANTS) for f in FIELDS} for k, _ in STAGES}
    grand = {f: sum(total[k][f] for k, _ in STAGES) for f in FIELDS}
    tokens_all = grand["input_tokens"] + grand["output_tokens"]

    lines = [
        "% Generated by report/tools/make_ex_tables.py from the Ex01 cost files; do not edit by hand.",
        "\\begin{tabular}{@{}lrrrrrr@{}}",
        "\\toprule",
        "Bước & Lượt gọi & Token vào & \\begin{tabular}[c]{@{}r@{}}trong đó\\\\đã lưu sẵn\\end{tabular}"
        " & Token ra & \\begin{tabular}[c]{@{}r@{}}Tỉ lệ\\\\tổng token\\end{tabular} & Thời gian (phút) \\\\",
        "\\midrule",
    ]
    for key, label in STAGES:
        t = total[key]
        share = (t["input_tokens"] + t["output_tokens"]) / tokens_all
        lines.append(
            f"{label} & {vn_int(t['calls_new'])} & {vn_int(t['input_tokens'])} & {vn_int(t['cached_input_tokens'])}"
            f" & {vn_int(t['output_tokens'])} & {vn_pct(share)} & {vn_float(t['stage_wall_seconds'] / 60)} \\\\"
        )
    lines += [
        "\\midrule",
        f"\\textbf{{Tổng}} & \\textbf{{{vn_int(grand['calls_new'])}}} & \\textbf{{{vn_int(grand['input_tokens'])}}}"
        f" & \\textbf{{{vn_int(grand['cached_input_tokens'])}}} & \\textbf{{{vn_int(grand['output_tokens'])}}}"
        f" & \\textbf{{100\\%}} & \\textbf{{{vn_float(grand['stage_wall_seconds'] / 60)}}} \\\\",
        "\\bottomrule",
        "\\end{tabular}",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")

    # numbers quoted in the report text, printed so the prose can be checked against the data
    try:
        shown = args.out.resolve().relative_to(ROOT)
    except ValueError:
        shown = args.out
    print("wrote", shown)
    print("total calls", vn_int(grand["calls_new"]), "retries", vn_int(grand["calls_retry"]),
          "missing usage", vn_int(grand["usage_missing_calls"]))
    print("input", vn_int(grand["input_tokens"]), "cached", vn_int(grand["cached_input_tokens"]),
          "uncached", vn_int(grand["input_tokens"] - grand["cached_input_tokens"]),
          "output", vn_int(grand["output_tokens"]))
    print("input share of all tokens", vn_pct(grand["input_tokens"] / tokens_all))
    print("minutes", vn_float(grand["stage_wall_seconds"] / 60, 2))
    for v in VARIANTS:
        calls = sum(per_variant[v][k]["calls_new"] for k, _ in STAGES)
        tok_in = sum(per_variant[v][k]["input_tokens"] for k, _ in STAGES)
        print(f"{v}: calls {vn_int(calls)}, input tokens {vn_int(tok_in)}")
    miss = {k: int(sum(per_variant[v][k]["usage_missing_calls"] for v in VARIANTS)) for k, _ in STAGES}
    print("missing usage by step", {k: m for k, m in miss.items() if m})
    for k, label in STAGES:
        c, i = total[k]["calls_new"], total[k]["input_tokens"]
        ok = c - miss[k]
        if ok > 0:
            print(f"  input tokens per call with usage, {label}: {vn_int(i / ok)}")


if __name__ == "__main__":
    main()
